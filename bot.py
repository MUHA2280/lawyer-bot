def _resolve_llm_config():
    """Автоопределение провайдера: OpenRouter (sk-or-*) vs OpenAI-совместимый."""
    key = OPENAI_API_KEY
    base = OPENAI_BASE_URL
    model = OPENAI_MODEL or "gpt-4o-mini"
    headers = {}
    if key.startswith("sk-or-") and not base:
        base = "https://openrouter.ai/api/v1"
        headers = {"HTTP-Referer": "https://telegram.org", "X-Title": "RF Law Telegram Bot"}
        # OpenRouter требует префикс провайдера: gpt-4o-mini -> openai/gpt-4o-mini
        if "/" not in model:
            low = model.lower()
            if low.startswith(("gpt-", "o1", "o3")):
                model = f"openai/{model}"
    return base, model, headers

async def ask_llm(user_text: str) -> str | None:
    """Возвращает ответ LLM или None при ошибке/отсутствии ключа."""
    if not OPENAI_API_KEY:
        return None
    try:
        from openai import AsyncOpenAI
        base, model, headers = _resolve_llm_config()
        client = AsyncOpenAI(api_key=OPENAI_API_KEY, base_url=base, default_headers=headers or None)
        resp = await client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_text},
            ],
            temperature=0.3,
            max_tokens=1500,
        )
        return resp.choices[0].message.content.strip()
    except Exception as e:
        log.error(f"LLM error: {e}")
        return None

