def detect_topic(text: str):
    t = text.lower()
    best = None
    best_score = 0
    for topic in KNOWLEDGE:
        score = sum(1 for k in topic["keys"] if k in t)
        if score > best_score:
            best_score = score
            best = topic
    return best if best_score > 0 else None

